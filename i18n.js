/* Pick a sensible first-visit language: saved choice → browser language. */
(function () {
  var lang = "en";
  try {
    var saved = localStorage.getItem("freq-lang");
    if (saved === "fa" || saved === "en") {
      lang = saved;
    } else {
      var list = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ""]) || [];
      for (var i = 0; i < list.length; i += 1) {
        if (/^fa\b/i.test(String(list[i]))) {
          lang = "fa";
          break;
        }
      }
    }
  } catch (_) {}
  window.FREQ_DEFAULT_LANG = lang;
  try {
    var pack = window.I18N[lang];
    document.documentElement.lang = pack.htmlLang;
    document.documentElement.dir = pack.dir;
    document.title = pack.title;
  } catch (_) {}
})();
